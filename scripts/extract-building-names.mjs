#!/usr/bin/env node
/**
 * One-off script: extracts a building/community name from each property's
 * imported title (e.g. "Shangri la 2bedrooms rent - Colombo 1" → "Shangri-La")
 * for the new properties.building_name column.
 *
 * Usage:
 *   Preview only (reads the database, writes nothing):
 *     node --env-file=.env.local scripts/extract-building-names.mjs
 *   Generate the SQL to apply (run it in the Supabase SQL editor):
 *     node --env-file=.env.local scripts/extract-building-names.mjs --write
 *   Output: supabase/seed/building-names.sql
 */
import { writeFile } from "node:fs/promises";
import { createClient } from "@supabase/supabase-js";

const OUT_PATH = "supabase/seed/building-names.sql";

// Spelling fixes and canonical names, keyed by the lowercased raw extraction.
// Anything not listed here is just title-cased.
const ALIASES = {
  "shangri la": "Shangri-La",
  "shnagri la": "Shangri-La",
  "capital height": "Capital Heights",
  "capital heights": "Capital Heights",
  "capital twin peaks": "Capital Twin Peaks",
  "cinnamon life residence": "Cinnamon Life",
  "cinnamon life suite tower": "Cinnamon Life Suites",
  "fairway sky gardens": "Sky Gardens",
  elelments: "Elements",
  ccc: "CCC",
  icc: "ICC",
  on320: "ON320",
  "jat residence": "JAT Residence",
};

const BEDROOMS = /\b\d+\s*bedr?\w*/i;
const LISTING_WORD = /\b(rent|sale)\b/i;
const FILLER = /\b(apa?p?rtment|for|at)\b/gi;

function extractBuildingName(title) {
  const cleaned = title.replace(/\.{2,}.*$/, "").replace(/\s+/g, " ").trim();

  const bedroomMatch = cleaned.match(BEDROOMS);
  const listingMatch = cleaned.match(LISTING_WORD);
  if (!bedroomMatch && !listingMatch && !ALIASES[cleaned.toLowerCase()]) {
    return null;
  }

  let raw;
  if (bedroomMatch && bedroomMatch.index === 0) {
    // "4 bedrooms Elements Rent - ..." → name sits after the bedroom count.
    const rest = cleaned.slice(bedroomMatch[0].length);
    raw = rest.split(LISTING_WORD)[0];
  } else {
    const cut = Math.min(
      bedroomMatch?.index ?? Infinity,
      listingMatch?.index ?? Infinity,
      cleaned.length,
    );
    raw = cleaned.slice(0, cut);
  }

  raw = raw.replace(FILLER, " ").replace(/[-–]/g, " ").replace(/\s+/g, " ").trim();
  if (!raw) return null;

  return (
    ALIASES[raw.toLowerCase()] ??
    raw
      .split(" ")
      .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
      .join(" ")
  );
}

const sqlString = (value) =>
  value === null ? "NULL" : `'${value.replace(/'/g, "''")}'`;

const supabase = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY,
);
const { data: properties, error } = await supabase
  .from("properties")
  .select("id, title")
  .order("title");
if (error) throw error;

const results = properties.map((p) => ({ ...p, name: extractBuildingName(p.title) }));

if (process.argv.includes("--write")) {
  const lines = [
    "-- Generated by scripts/extract-building-names.mjs -- do not edit by hand.",
    "alter table public.properties add column if not exists building_name text;",
    "",
    ...results.map(
      (r) => `update public.properties set building_name = ${sqlString(r.name)} where id = '${r.id}';`,
    ),
  ];
  await writeFile(OUT_PATH, `${lines.join("\n")}\n`);
  console.log(`Wrote ${results.length} updates to ${OUT_PATH}`);
} else {
  for (const r of results) console.log(`${r.title}  →  ${r.name ?? "(null)"}`);

  const counts = {};
  for (const r of results) counts[r.name ?? "(null)"] = (counts[r.name ?? "(null)"] ?? 0) + 1;
  console.log("\n--- Distinct names ---");
  for (const [name, count] of Object.entries(counts).sort()) console.log(`${String(count).padStart(3)}  ${name}`);
}
